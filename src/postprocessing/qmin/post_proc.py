#!/usr/bin/env python3
"""
QMIN scan post-processing (Python / Polars port of the Go `qmin` package).

Design for low RAM + many large input files
-------------------------------------------
* Inputs are only ever *scanned* lazily (`pl.scan_parquet`), never loaded.
* All work is expressed as one lazy query per output file and written with
  `sink_parquet`, so the streaming engine processes the data in batches.
  Peak memory ~ number of distinct resolvers, not number of rows.
* The per-row Go logic (`evalRow`) is expressed as vectorised expressions.
  Only `analyze_pattern` stays in plain Python, and it runs once per *distinct*
  scan pattern (after the per-resolver ID label is normalised), not per row.
* MaxMind lookups happen *after* aggregation (one row per resolver / pair)
  inside `map_batches`, with an LRU cache. No giant IP lookup tables.
* The Go `combineResults` TriBool merge is replaced by associative boolean
  flags (seen_true / seen_false) -> NIL / FALSE / TRUE / UNCERTAIN at the end.

Requirements:  pip install "polars>=1.31" maxminddb

Usage:
  python qmin_postprocess.py INPUT_DIR [--recursive] [--combine]
         [--out DIR] [--pattern-matching] [--metadata FILE]
         [--asn-db data/external/GeoLite2-ASN.mmdb]
         [--country-db data/external/GeoLite2-Country.mmdb]

Tip: cap resources with POLARS_MAX_THREADS=<n> if RAM is really tight.
"""
