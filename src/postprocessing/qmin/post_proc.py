# --------------------------------------------------------------------------- #
# Metadata
# --------------------------------------------------------------------------- #
@dataclass
class Metadata:
    """Metadata of one scan run (keys matched case-insensitively, like Go's json)."""
    Start: str = ""
    Fin: str = ""
    Runtime: str = ""
    Input: str = ""
    NumResolver: int = 0
    Timeout: int = 0
    RetryTimeout: int = 0
    Protocol: str = ""
    LabelDepth: int = 0
    Rounds: int = 0
    BaseURL: str = ""

    @classmethod
    def from_file(cls, path: Path | str) -> "Metadata":
        with open(path, encoding="utf-8") as f:
            raw = json.load(f)
        lowered = {k.lower(): v for k, v in raw.items()}
        return cls(**{f.name: lowered[f.name.lower()]
                      for f in fields(cls) if f.name.lower() in lowered})

    @property
    def base_label_count(self) -> int:
        """Number of labels of the base domain used during the scan."""
        n = self.BaseURL.count(".")
        return n if self.BaseURL.endswith(".") else n + 1


# --------------------------------------------------------------------------- #
# Pattern analysis (runs once per distinct pattern)
# --------------------------------------------------------------------------- #
def analyze_pattern(pattern: str, base_labels: int) -> tuple[bool, str, int, int]:
    """
    Transform the scan pattern into the pattern format from the papers and
    extract max/min (according to the QMIN RFC 9156) rule estimations.
    A scan pattern looks like:
      23.22.21...4_TXT|3_NS|2_NS|1_NS|*ip*-24-645_NS
    Returns (qmin, qmin_pattern, max, min).
    """
    # no qmin behaviour
    if "|" not in pattern:
        # weird patterns with only a single label
        if "." not in pattern:
            return False, pattern, 0, 0
        parts = pattern.split("_")
        if len(parts) < 2:
            raise ValueError(f"Malformed pattern: {pattern}")
        # label depth 24 + 2 label base domain -> "26TXT"
        return False, f"{pattern.count('.') + 1 + base_labels}{parts[1]}", 1, 1

    max_ = pattern.count("|") + 1
    min_ = 0
    qmin_pattern = ""
    min_boundary_reached = False  # labels handled via primitive QMIN
    for part in reversed(pattern.split("|")):
        if not min_boundary_reached and part.count(".") == 0:
            min_ += 1
        else:
            min_boundary_reached = True
        split1 = part.split("_")
        split2 = split1[0].split(".")

        # the ID label (first one)
        if len(split2) == 1 and "-" in split2[0]:
            qmin_pattern = f"{1 + base_labels}{split1[1]}"
            continue
        # everything else (+1 because of the id label)
        stage = int(split2[0])
        qmin_pattern = f"{stage + 1 + base_labels}{split1[1]}-{qmin_pattern}"
    return True, qmin_pattern, max_, min_


# --------------------------------------------------------------------------- #
# MaxMind enrichment (applied after aggregation, batch-wise, cached)
# --------------------------------------------------------------------------- #
GEO_DTYPE = pl.Struct({"asn": pl.UInt64, "org": pl.String, "country": pl.String})


class GeoEnricher:
    def __init__(self, asn_path: str, country_path: str, cache_size: int = 1 << 20):
        self._asn = maxminddb.open_database(asn_path)
        self._country = maxminddb.open_database(country_path)
        self._cached_lookup = lru_cache(maxsize=cache_size)(self._lookup)

    def close(self) -> None:
        self._asn.close()
        self._country.close()

    def _lookup(self, ip: str) -> dict:
        asn, org, cc = 0, "", ""
        try:
            rec = self._asn.get(ip) or {}
            asn = rec.get("autonomous_system_number", 0) or 0
            org = rec.get("autonomous_system_organization", "") or ""
            rec = self._country.get(ip) or {}
            cc = (rec.get("registered_country") or {}).get("iso_code", "") or ""
        except (ValueError, TypeError):  # malformed IP / IPv6 in IPv4-only db
            pass
        return {"asn": asn, "org": org, "country": cc}

    def _batch(self, s: pl.Series) -> pl.Series:
        return pl.Series([self._cached_lookup(ip or "") for ip in s], dtype=GEO_DTYPE)

    def enrich(self, lf: pl.LazyFrame, col: str, prefix: str) -> pl.LazyFrame:
        """Adds <prefix>_asn, <prefix>_org, <prefix>_country."""
        return (
            lf.with_columns(
                pl.col(col)
                .map_batches(self._batch, return_dtype=GEO_DTYPE, is_elementwise=True)
                .alias("_geo")
            )
            .with_columns(
                pl.col("_geo").struct.field("asn").alias(f"{prefix}_asn"),
                pl.col("_geo").struct.field("org").alias(f"{prefix}_org"),
                pl.col("_geo").struct.field("country").alias(f"{prefix}_country"),
            )
            .drop("_geo")
        )


# --------------------------------------------------------------------------- #
# Row evaluation (vectorised port of evalRow)
# --------------------------------------------------------------------------- #
def annotate_rows(dir_path: Path, md: Metadata, pattern_matching: bool) -> pl.LazyFrame:
    """
    Lazily scan one result.parquet and classify every row (column `kind`):

      strict   RequestingIP == NONE, mode check, response nxdomain
      nx       NXDOMAIN-optimisation check (NONE or not)
      error    RequestingIP == NONE for any other reason
      mode     QMIN mode check with a requesting IP (relaxed if '|' in response)
      induced  QMIN check on CNAME-induced resolution
      qmin     normal QMIN behaviour -> pattern analysis

    Branch order is identical to the Go if/else chain.
    """
    c = INPUT_COLUMNS
    lf = pl.scan_parquet(dir_path / "result.parquet").select(
        pl.col(c["queried_ip"]).alias("queried_ip"),
        pl.col(c["resolver_type"]).fill_null("").alias("resolver_type"),
        pl.col(c["requesting_ip"]).fill_null("").alias("requesting_ip"),
        pl.col(c["response"]).fill_null("").alias("response"),
        pl.col(c["qmin_mode_check"]).fill_null(False).alias("qmin_mode_check"),
        pl.col(c["nx_check"]).fill_null(False).alias("nx_check"),
        pl.col(c["nxOptimization"]).cast(pl.Int8).fill_null(NIL).alias("nxOptimization"),
        pl.col(c["induced_qmin_check"]).fill_null(False).alias("induced_qmin_check"),
        pl.col(c["induced_res"]).fill_null("").alias("induced_res"),
        pl.col(c["filename"]).fill_null("").alias("filename"),
    )

    resp = pl.col("response")
    is_none = pl.col("requesting_ip") == "NONE"
    mode, nx, ind = pl.col("qmin_mode_check"), pl.col("nx_check"), pl.col("induced_qmin_check")

    kind = (
        pl.when(is_none & mode & (resp == "nxdomain")).then(pl.lit("strict"))
        .when(is_none & nx).then(pl.lit("nx"))
        .when(is_none).then(pl.lit("error"))
        .when(mode).then(pl.lit("mode"))
        .when(nx).then(pl.lit("nx"))
        .when(ind).then(pl.lit("induced"))
        .otherwise(pl.lit("qmin"))
    )
    lf = lf.with_columns(kind.alias("kind"))

    # normalised pattern key (only rows that need pattern analysis)
    dotted_or_piped = resp.str.contains(".", literal=True) | resp.str.contains("|", literal=True)
    pat_key = pl.when(pl.col("kind") == "qmin").then(
        pl.when(dotted_or_piped)  # single-label "weird" patterns stay untouched
        .then(resp.str.replace_all(ID_LABEL_RE, ID_LABEL_PLACEHOLDER))
        .otherwise(resp)
    )
    lf = lf.with_columns(pat_key.alias("pat_key"))

    # analyse every distinct pattern once (tiny set), then join the result back
    uniques = (
        lf.filter(pl.col("pat_key").is_not_null())
        .select("pat_key").unique()
        .collect(engine="streaming")["pat_key"].to_list()
    )
    cols: dict[str, list] = {k: [] for k in
                             ("pat_key", "qmin_ok", "qmin_pattern", "max_min", "pattern_match")}
    for p in uniques:
        qmin, pat, mx, mn = analyze_pattern(p, md.base_label_count)
        if pattern_matching:
            match = KNOWN_RESOLVER_PATTERN.get(pat, ["none"])
        else:
            match = ["unset"]
        cols["pat_key"].append(p)
        cols["qmin_ok"].append(qmin)
        cols["qmin_pattern"].append(pat)
        cols["max_min"].append(f"{mx}-{mn}")
        cols["pattern_match"].append(match)
    lookup = pl.DataFrame(cols, schema={
        "pat_key": pl.String, "qmin_ok": pl.Boolean, "qmin_pattern": pl.String,
        "max_min": pl.String, "pattern_match": pl.List(pl.String)})

    return (
        lf.join(lookup.lazy(), on="pat_key", how="left")
        .drop("pat_key")
        .with_columns(pl.lit(md.Protocol).alias("protocol"))
    )


def _tribool(seen_true: str, seen_false: str) -> pl.Expr:
    """Equivalent of the Go TriBool merge (Nil / False / True / Uncertain)."""
    t, f = pl.col(seen_true), pl.col(seen_false)
    return (
        pl.when(t & f).then(pl.lit(UNCERTAIN, dtype=pl.Int8))
        .when(t).then(pl.lit(TRUE, dtype=pl.Int8))
        .when(f).then(pl.lit(FALSE, dtype=pl.Int8))
        .otherwise(pl.lit(NIL, dtype=pl.Int8))
    )


FLAG_COLS = ["qmin_t", "qmin_f", "ind_t", "ind_f", "nx_t", "nx_f", "mode_strict", "mode_relaxed"]


def resolver_pipeline(rows: pl.LazyFrame, geo: GeoEnricher) -> pl.LazyFrame:
    """One output row per (protocol, queried_ip)  ->  analysed_resolver.parquet"""
    k = pl.col("kind")
    pipe = pl.col("response").str.contains("|", literal=True)
    induced_pipe = pl.col("induced_res").str.contains("|", literal=True)

    # level 1: (protocol, ip, err_key). err_key makes the Go `Errors` map
    # aggregable without a join; it is NULL for every non-error row.
    lvl1 = (
        rows.with_columns(
            pl.when(k == "error").then(pl.col("response")).alias("err_key"))
        .group_by("protocol", "queried_ip", "err_key")
        .agg(
            pl.len().cast(pl.Int64).alias("count"),
            pl.col("resolver_type").first(),
            pl.col("filename").first(),
            pl.col("requesting_ip").filter(pl.col("requesting_ip") != "NONE")
              .unique(maintain_order=True).alias("requesting_ips"),
            ((k == "qmin") & pl.col("qmin_ok")).any().alias("qmin_t"),
            ((k == "qmin") & ~pl.col("qmin_ok")).any().alias("qmin_f"),
            ((k == "induced") & induced_pipe).any().alias("ind_t"),
            ((k == "induced") & ~induced_pipe).any().alias("ind_f"),
            ((k == "nx") & (pl.col("nxOptimization") == TRUE)).any().alias("nx_t"),
            ((k == "nx") & (pl.col("nxOptimization") == FALSE)).any().alias("nx_f"),
            (k == "strict").any().alias("mode_strict"),
            ((k == "mode") & pipe).any().alias("mode_relaxed"),
        )
    )

    # level 2: (protocol, ip)
    lvl2 = lvl1.group_by("protocol", "queried_ip").agg(
        pl.col("count").sum(),
        pl.col("resolver_type").first(),
        pl.col("filename").first(),
        pl.col("requesting_ips").explode().drop_nulls().unique(maintain_order=True),
        *[pl.col(c).any() for c in FLAG_COLS],
        pl.struct(key=pl.col("err_key"), value=pl.col("count"))
          .filter(pl.col("err_key").is_not_null()).alias("errors"),
    )

    strict, relaxed = pl.col("mode_strict"), pl.col("mode_relaxed")
    qmin_mode = (
        pl.when(strict & relaxed).then(pl.lit("both"))
        .when(strict).then(pl.lit("strict"))
        .when(relaxed).then(pl.lit("relaxed"))
        .otherwise(pl.lit(""))
    )

    return geo.enrich(lvl2, "queried_ip", "queried_ip").select(
        "protocol",
        "queried_ip",
        "queried_ip_asn",
        "queried_ip_org",
        "queried_ip_country",
        "resolver_type",
        "requesting_ips",
        _tribool("qmin_t", "qmin_f").alias("qmin_enabled"),
        _tribool("ind_t", "ind_f").alias("induction_qmin"),
        qmin_mode.alias("qmin_mode"),
        _tribool("nx_t", "nx_f").alias("nxOptimization"),
        "errors",
        "count",
        pl.col("filename").alias("filename"),
    )


def pair_pipeline(rows: pl.LazyFrame, geo: GeoEnricher) -> pl.LazyFrame:
    """One output row per (resolver, requesting IP, pattern)  ->  pattern.parquet"""
    lf = (
        rows.filter(pl.col("kind") == "qmin")
        .group_by("protocol", "queried_ip", "requesting_ip", "qmin_pattern")
        .agg(
            pl.len().cast(pl.Int64).alias("count"),
            pl.col("resolver_type").first(),
            pl.col("qmin_ok").first().alias("qmin_enabled"),
            pl.col("max_min").first().alias("max_min_rfc_9156"),
            pl.col("pattern_match").first().alias("resolver_pattern_match"),
        )
    )
    lf = geo.enrich(lf, "queried_ip", "queried_ip")
    lf = geo.enrich(lf, "requesting_ip", "requesting_ip")
    return lf.select(
        "protocol",
        "queried_ip", "queried_ip_asn", "queried_ip_org", "queried_ip_country",
        "requesting_ip", "requesting_ip_asn", "requesting_ip_org", "requesting_ip_country",
        "resolver_type", "qmin_enabled", "qmin_pattern", "resolver_pattern_match",
        "max_min_rfc_9156", "count",
    )


# --------------------------------------------------------------------------- #
# Directory handling / entry points
# --------------------------------------------------------------------------- #
def find_input_dirs(base: Path, require_metadata: bool) -> list[Path]:
    """All directories below `base` (incl. itself) that contain a result.parquet."""
    out = []
    for root, dirnames, files in os.walk(base):
        dirnames.sort()
        if "result.parquet" not in files:
            continue
        if require_metadata and "metadata.json" not in files:
            continue
        out.append(Path(root))
    return out


def process_dirs(dirs: list[Path], out_dir: Path, geo: GeoEnricher,
                 pattern_matching: bool, metadata_path: str,
                 write_scan_metadata: bool = False) -> None:
    if not dirs:
        log.warning("No valid input directories found (skipping)")
        return

    frames, first_md = [], None
    for d in dirs:
        md_file = Path(metadata_path) if metadata_path else d / "metadata.json"
        if not md_file.exists():
            log.warning('metadata.json does not exist: "%s" (skipping %s)', md_file, d)
            continue
        log.info("Now processing: %s", d)
        md = Metadata.from_file(md_file)
        first_md = first_md or md
        frames.append(annotate_rows(d, md, pattern_matching))
    if not frames:
        return

    rows = pl.concat(frames)  # lazy, nothing is read yet
    out_dir.mkdir(parents=True, exist_ok=True)

    if write_scan_metadata and first_md is not None:
        (out_dir / "scan_metadata.json").write_text(json.dumps(asdict(first_md)))

    # two streaming passes over the (column-pruned) input
    resolver_pipeline(rows, geo).sink_parquet(
        out_dir / "analysed_resolver.parquet", compression="zstd")
    pair_pipeline(rows, geo).sink_parquet(
        out_dir / "pattern.parquet", compression="zstd")


def start_post_processing(input_path: str, recursive: bool = False, outpath: str = "",
                          pattern_matching: bool = False, combine: bool = False,
                          metadata_path: str = "",
                          asn_db: str = "data/external/GeoLite2-ASN.mmdb",
                          country_db: str = "data/external/GeoLite2-Country.mmdb") -> None:
    """Main function of this module (port of StartPostProcessing)."""
    out_base = Path(outpath) if outpath else Path("src/data/processed/qmin")
    run_dir = out_base / datetime.now().strftime("%Y-%m-%d_%H-%M")
    inp = Path(input_path)

    geo = GeoEnricher(asn_db, country_db)
    try:
        if recursive and not combine:
            # every valid directory is processed on its own
            for d in find_input_dirs(inp, require_metadata=not metadata_path):
                process_dirs([d], run_dir / d.name, geo, pattern_matching, metadata_path)
        elif combine:
            # all valid directories end up in one result
            dirs = find_input_dirs(inp, require_metadata=not metadata_path)
            process_dirs(dirs, run_dir, geo, pattern_matching, metadata_path)
        else:
            if not (inp / "result.parquet").exists():
                log.warning('result.parquet does not exist in "%s" (skipping)', inp)
                return
            process_dirs([inp], run_dir, geo, pattern_matching, metadata_path,
                         write_scan_metadata=True)
    finally:
        geo.close()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("input_path")
    ap.add_argument("--recursive", action="store_true")
    ap.add_argument("--combine", action="store_true")
    ap.add_argument("--out", default="")
    ap.add_argument("--pattern-matching", action="store_true")
    ap.add_argument("--metadata", default="")
    ap.add_argument("--asn-db", default="src/data/external/GeoLite2-ASN.mmdb")
    ap.add_argument("--country-db", default="src/data/external/GeoLite2-Country.mmdb")
    a = ap.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(message)s", stream=sys.stdout)
    start_post_processing(a.input_path, a.recursive, a.out, a.pattern_matching,
                          a.combine, a.metadata, a.asn_db, a.country_db)


if __name__ == "__main__":
    main()